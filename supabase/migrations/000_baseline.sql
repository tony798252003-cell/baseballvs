-- Baseline schema, reproduced from the live database (PostgREST OpenAPI, 2026-10-23).
-- No behavior change: every statement is "if not exists".

create table if not exists players (
  id integer generated by default as identity primary key,
  name text not null,
  number text not null,
  team text,
  original_team text,
  photo text,
  song text,
  emoji text,
  intro text,
  eye_mask_position text,
  main_position text,
  other_positions text,
  pitching_hand text default '右',
  batting_hand text default '右',
  created_at timestamptz default now(),
  cpbl_acnt text unique,
  is_coach boolean default false,
  league text default '一軍'
);

create table if not exists team_chants (
  id uuid primary key default gen_random_uuid(),
  team text not null,
  name text not null,
  url text not null,
  created_at timestamptz default now()
);
